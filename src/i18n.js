export const getLanguage = () => localStorage.getItem(LANGUAGE_KEY) === "en" ? "en" : "ar";

export const setLanguage = (language) => {
  const nextLanguage = language === "en" ? "en" : "ar";
  localStorage.setItem(LANGUAGE_KEY, nextLanguage);
  listeners.forEach((listener) => listener(nextLanguage));
};

export const useLanguage = () => {
  const [language, setCurrentLanguage] = useState(getLanguage);
  useEffect(() => {
    const update = (nextLanguage) => setCurrentLanguage(nextLanguage);
    listeners.add(update);
    return () => listeners.delete(update);
  }, []);
  return { language, isArabic: language === "ar", dir: language === "ar" ? "rtl" : "ltr" };
};

export const t = (text) => {
  if (typeof text !== "string") return text;
  const key = normalizeTranslationKey(text);
  const language = getLanguage();
  const translation = language === "en"
    ? normalizedTranslations[key]
    : apiLabelsArabic[key.toLocaleLowerCase()] || reverseTranslations[key.toLocaleLowerCase()];
  if (!translation) return text;
  const leadingSpace = /^[\t ]/.test(text) ? " " : "";
  const trailingSpace = /[\t ]$/.test(text) ? " " : "";
  return `${leadingSpace}${translation}${trailingSpace}`;
};
